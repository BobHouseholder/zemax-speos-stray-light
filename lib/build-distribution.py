# Files referenced as `os.path.join(BASE, "x")` or `$BASE\x` by shipped code.
# `[A-Za-z0-9]+` for the extension, NOT `[a-z]+`: the scan that first built
# ROOT_FILES used the latter and so could never match `ps1`, silently hiding
# every PowerShell script at the root. That single character is why the
# distribution shipped broken.
# MULTI-SEGMENT on purpose: the single-segment version caught export-odx.ps1
# and then missed os.path.join(BASE, "ghost", "s0-ghosts.ps1") one stage later,
