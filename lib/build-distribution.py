"""build-distribution.py -- assemble the shippable pipeline. Allowlist only.

    python lib/build-distribution.py [--out DIR] [--with-testcases] [--check]

      --out             where to build (default: ../straylight-pipeline)
      --with-testcases  include the regression suite's source
      --check           verify an existing build; write nothing, exit non-zero
                        if anything is wrong

WHY AN ALLOWLIST AND NEVER A DIRECTORY COPY
-------------------------------------------
`lib/` and `survey/` hold 530 MB, of which 266 KB is source. The other 99.95%
is run output -- 88 .lpf ray files at 450 MB, 643 .xmp result maps, 643 Speos
HTML reports, 83 SpaceClaim documents. A recursive copy ships all of it.

Size is the least of it. Three things in that tree must never leave:

  * `lib/fleet-codever.log` and `survey/wide100-couplegate.log` contain licence
    error text quoting the Ansys ACCOUNT NUMBER.
  * The 22 `.zmx` prescriptions are Zemax's sample lenses. The corpus export
    already established they are not ours to redistribute; a directory copy
    would quietly reverse that decision.
  * `straylight.toml` describes ONE machine. Shipping it means a customer
    inherits paths that do not exist, and the config check they were told to
    run passes on a file they never wrote. Only the `.example` ships.

So the rule is inverted from the usual: nothing is included unless a rule below
names it, and everything excluded is COUNTED and reported. A build that
silently dropped a needed file would look exactly like a clean build.
"""
